import type { LlmChunk } from "./index";

/** Системный промпт: текст, не логика. */
export const LLM_SYSTEM_PROMPT = `Ты — аккуратный редактор-корректор русскоязычных расшифровок и документов.
Твоя задача — исправить орфографию, пунктуацию, опечатки и остаточные артефакты речи, не меняя смысл и структуру текста.

Критически важные правила:
- Ссылки (http/https), e-mail, домены, имена файлов, код в backticks и числа копируй ДОСЛОВНО, символ в символ. Не сокращай, не «исправляй» и не удаляй их.
- Не выбрасывай и не добавляй смысловые блоки, предложения и абзацы. Не сокращай и не переписывай своими словами.
- Сохраняй количество и порядок абзацев, списков и переносов строк как в оригинале.
- Если фрагмент выглядит как обрывок или ошибка распознавания — аккуратно восстанови по смыслу, но не удаляй сам факт.
- Не добавляй заголовки, комментарии, Markdown-ограждения, пояснения и приветствия.
- Верни только исправленный текст, без кавычек и обрамления.`;

export function buildUserMessage(chunk: LlmChunk): string {
  const parts: string[] = [];
  if (chunk.contextBefore) {
    parts.push(`Контекст до (только для понимания, не для вывода):\n${chunk.contextBefore}`);
  }
  if (chunk.contextAfter) {
    parts.push(`Контекст после (только для понимания, не для вывода):\n${chunk.contextAfter}`);
  }
  parts.push(`Текст для правки:\n${chunk.text}`);
  return parts.join("\n\n");
}